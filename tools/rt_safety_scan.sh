#!/usr/bin/env bash
# Real-time safety scan for the audio path (CLAUDE.md section 3).
# Flags forbidden calls in core/, drivers/ and dsp/: heap allocation, mutexes, exceptions,
# SCHED_FIFO/SCHED_RR and mlock. Comments and string literals are ignored.
#
# Known hits live in tools/rt_safety_baseline.txt. The scan fails only on hits that are not in
# the baseline, so existing debt is visible and cannot grow. Remove a baseline line when its
# code is fixed. Regenerate the baseline with --update-baseline only with a reviewer's approval.
#
#   tools/rt_safety_scan.sh                    check against the baseline
#   tools/rt_safety_scan.sh --update-baseline  rewrite the baseline from the current tree
set -euo pipefail

repo_root="$(cd "$(dirname "$0")/.." && pwd)"
scan_root="$repo_root/src/app/src/main/cpp"
baseline="$repo_root/tools/rt_safety_baseline.txt"
scan_dirs=(core drivers dsp)

# rule name : extended regex applied to code with comments and strings removed
# mawk has no \b, so word boundaries are spelled out as "start or non-identifier character".
# Patterns avoid backslashes: awk -v processes escape sequences, so use [(] for a literal paren.
w='(^|[^A-Za-z0-9_])'
e='([^A-Za-z0-9_]|$)'
rules=(
    "heap-new:${w}new${e}"
    "heap-malloc:${w}(malloc|calloc|realloc)[[:space:]]*[(]"
    'mutex:std::(recursive_|timed_)?mutex|std::(lock_guard|unique_lock|scoped_lock)'
    "exception:${w}throw${e}"
    "sched-fifo-rr:${w}SCHED_(FIFO|RR)${e}"
    "mlock:${w}mlock(all)?[[:space:]]*[(]"
)

# Prints "relative/path<TAB>rule<TAB>trimmed source line" for every hit.
collect_hits() {
    local dir file
    for dir in "${scan_dirs[@]}"; do
        while IFS= read -r -d '' file; do
            awk -v rel="${file#"$scan_root"/}" -v rules="$(printf '%s\n' "${rules[@]}")" '
                BEGIN {
                    n = split(rules, lines, "\n")
                    for (i = 1; i <= n; i++) {
                        p = index(lines[i], ":")
                        names[i] = substr(lines[i], 1, p - 1)
                        pats[i] = substr(lines[i], p + 1)
                    }
                    in_block = 0
                }
                {
                    raw = $0
                    code = raw
                    # Drop /* ... */ blocks that open and close on this line, and track multi-line ones.
                    if (in_block) {
                        e = index(code, "*/")
                        if (e == 0) next
                        code = substr(code, e + 2)
                        in_block = 0
                    }
                    while ((s = index(code, "/*")) > 0) {
                        e = index(substr(code, s + 2), "*/")
                        if (e == 0) { code = substr(code, 1, s - 1); in_block = 1; break }
                        code = substr(code, 1, s - 1) substr(code, s + 2 + e + 1)
                    }
                    # Drop string and char literals, then line comments.
                    gsub(/"([^"\\]|\\.)*"/, "\"\"", code)
                    gsub(/\x27([^\x27\\]|\\.)*\x27/, "\x27\x27", code)
                    c = index(code, "//")
                    if (c > 0) code = substr(code, 1, c - 1)
                    # Includes such as <new> are not allocations.
                    if (code ~ /^[[:space:]]*#/) next
                    for (i = 1; i <= n; i++) {
                        if (code ~ pats[i]) {
                            trimmed = raw
                            sub(/^[[:space:]]+/, "", trimmed)
                            sub(/[[:space:]]+$/, "", trimmed)
                            printf "%s\t%s\t%s\n", rel, names[i], trimmed
                        }
                    }
                }
            ' "$file"
        done < <(find "$scan_root/$dir" \( -name '*.hpp' -o -name '*.cpp' -o -name '*.h' \) -print0 | sort -z)
    done
}

current="$(mktemp)"
trap 'rm -f "$current"' EXIT
collect_hits | sort > "$current"

if [[ "${1:-}" == "--update-baseline" ]]; then
    {
        echo "# Known real-time safety hits (path, rule, source line). Generated by tools/rt_safety_scan.sh."
        echo "# Each line is debt to fix in core/, drivers/ or dsp/. Do not add lines to hide new hits."
        cat "$current"
    } > "$baseline"
    echo "Baseline written: $(wc -l < "$current") hit(s) -> ${baseline#"$repo_root"/}"
    exit 0
fi

# Multiset comparison: each baseline line can cover one identical hit.
known="$(mktemp)"
trap 'rm -f "$current" "$known"' EXIT
if [[ -f "$baseline" ]]; then
    grep -v '^#' "$baseline" | sed '/^$/d' > "$known" || true
fi

new_hits="$(awk -F'\t' '
    FNR == NR { allowed[$0]++; next }
    { if (allowed[$0] > 0) allowed[$0]--; else print }
' "$known" "$current")"

total="$(wc -l < "$current" | tr -d ' ')"
if [[ -z "$new_hits" ]]; then
    echo "RT safety scan passed: $total known hit(s), none new."
    exit 0
fi

echo "RT safety scan FAILED. New forbidden calls in the audio path:"
echo "$new_hits" | awk -F'\t' '{ printf "  %s:%s  %s\n", $1, $2, $3 }'
echo "Fix them, or file the reproduction as an issue for the owning model before adding a baseline line."
exit 1
